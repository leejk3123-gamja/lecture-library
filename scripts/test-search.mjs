import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../site/assets');
const elements=Object.fromEntries(['materials-list','search','category','result-count','empty'].map(id=>[id,{value:id==='category'?'all':'',textContent:'',innerHTML:'',hidden:false,addEventListener(){}}]));
const context=vm.createContext({window:{},document:{querySelector:selector=>elements[selector.slice(1)]}});
vm.runInContext(fs.readFileSync(path.join(root,'materials.js'),'utf8'),context);
vm.runInContext(fs.readFileSync(path.join(root,'app.js'),'utf8'),context);
const render=()=>vm.runInContext('render()',context);
assert.equal(elements['result-count'].textContent,'총 3개 강의');
elements.search.value='중앙값';render();assert.equal(elements['result-count'].textContent,'총 1개 강의');
assert(elements['materials-list'].innerHTML.includes('statistics.html'));
elements.category.value='math';render();assert.equal(elements.empty.hidden,false);
elements.search.value='';render();assert.equal(elements['result-count'].textContent,'총 1개 강의');
elements.category.value='all';elements.search.value='gItHuB';render();assert(elements['materials-list'].innerHTML.includes('github-pages.html'));
elements.search.value='검색결과없음';render();assert.equal(elements['materials-list'].innerHTML,'');
elements.search.value='';context.window.LECTURES[0].title='<img src=x onerror=alert(1)>';render();assert(!elements['materials-list'].innerHTML.includes('<img src=x'));
assert.throws(()=>vm.runInContext("safePath('javascript:alert(1)')",context));
assert.throws(()=>vm.runInContext("safePath('materials/../secret.txt')",context));
console.log('검색·분류·빈 결과·대소문자·출력 이스케이프·경로 제한 검사 통과');
